#!/usr/bin/env node
/** Refresh retrieval metadata and the existing llms.txt documentation snapshots. */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const read = (path) => readFileSync(join(root, path), 'utf8');
const canonical = (path) => relative(root, path).split(sep).join('/');
const indexPath = 'docs/high_signal_file_index.json';
const old = existsSync(join(root, indexPath)) ? JSON.parse(read(indexPath)) : { files: [] };
const previous = new Map(old.files.map((entry) => [entry.path, entry]));
function list(directory) {
  return readdirSync(join(root, directory), { withFileTypes: true }).flatMap((entry) => {
    if (entry.name.startsWith('.') || entry.name === '__pycache__') return [];
    const path = `${directory}/${entry.name}`;
    if (entry.isDirectory()) return list(path);
    return /\.(?:js|mjs|py|html|css|yml|yaml)$/.test(entry.name) ? [path] : [];
  });
}
const paths = ['manifest.json', 'package.json', ...['src', 'scripts', 'test', '.github/workflows'].flatMap(list)].sort();
const files = paths.map((path) => {
  const body = read(path);
  const saved = previous.get(path);
  const kind = path.startsWith('test/') ? 'test' : path.startsWith('scripts/') ? 'tooling'
    : path.endsWith('.css') ? 'style' : path.endsWith('.html') ? 'markup'
    : path.startsWith('src/') ? 'source' : 'config';
  const description = saved?.description?.replace(/^\d+ tests:/, 'Tests:') ??
    (path.startsWith('test/') ? `Behavioral regression tests for ${path.split('/').at(-1)}.`
      : body.match(/\/\*\*\s*\n\s*\*\s*([^\n]+)/)?.[1] ?? `Maintained ${kind}: ${path}.`);
  const depends_on = [...body.matchAll(/\bfrom\s+['"]([.][^'"]+)['"]/g)]
    .map((match) => canonical(resolve(root, dirname(path), match[1])))
    .filter((path) => existsSync(join(root, path)));
  return {
    path, kind, lines: body.split('\n').length - (body.endsWith('\n') ? 1 : 0), description,
    exports: [...body.matchAll(/^export\s+(?:async\s+)?function\s+(\w+)/gm)].map((match) => match[1]),
    depends_on,
  };
});
const pkg = JSON.parse(read('package.json'));
const manifest = JSON.parse(read('manifest.json'));
const header = '<!-- generated by npm run docs:generate; repository source snapshots -->\n\n';
const docs = ['README.md', 'CLAUDE.md', 'docs/ARCHITECTURE.md', 'docs/COMPONENTS.md',
  'docs/SECURITY.md', 'docs/TESTING.md', 'docs/known-issues.md', 'PRIVACY.md',
  'docs/DEVELOPMENT.md', 'docs/wiki/index.md', 'docs/MCP.md', 'docs/external-calls.md'];
const outputs = new Map([
  [indexPath, `${JSON.stringify({ schema: 'high-signal-file-index/1', repository: pkg.name,
    note: 'Runtime, tools, tests and CI. Regenerate with npm run docs:generate; validate with npm run lint:docs.', files }, null, 2)}\n`],
  ['llms-full.txt', header + docs.map((path) => `---\ntitle: ${path}\nurl: https://github.com/mithudso/${pkg.name}/blob/main/${path}\n---\n\n${read(path).trimEnd()}\n`).join('\n')],
  ['llms-small.txt', header + `# ${manifest.name}\n\n` +
    `MV3 extension v${manifest.version}; Chrome ${manifest.minimum_chrome_version}+. Exports captions locally through Download PDF, Print and Copy. [src: manifest.json; README.md]\n\n` +
    `The worker tries direct caption downloads, then an injected transcript-panel reader. Direct fetches omit credentials; a normal panel tab can use its existing session. Panel language is unverified; explicit language selection requires a direct download. [src: src/background/service-worker.js]\n\n` +
    `The PDF writer uses Latin-1; Print preserves Unicode through Chrome. Pure modules under src/lib/ use no chrome.* APIs. [src: src/lib/pdf.js; docs/COMPONENTS.md]\n\n` +
    `Node ${pkg.engines.node}; no npm dependencies. Run npm run check and npm run build. Optional image tooling uses Python and Pillow. [src: package.json; docs/DEVELOPMENT.md]\n`],
  ['llms-facts.txt', header + '# Sourced facts\n\n' +
    `- Version ${manifest.version}; minimum Chrome ${manifest.minimum_chrome_version}. [src: manifest.json]\n` +
    `- Permissions: ${manifest.permissions.join(', ')}. [src: manifest.json]\n` +
    `- Host permissions: ${manifest.host_permissions.join(', ')}. [src: manifest.json]\n` +
    `- Node tooling requires ${pkg.engines.node}; npm dependencies are absent. [src: package.json]\n` +
    `- Check command: ${pkg.scripts.check}. [src: package.json]\n` +
    '- Direct requests omit credentials and reject redirects. Panel tabs follow normal browser sessions. [src: src/background/service-worker.js]\n' +
    '- Each Print handoff uses a separate session-storage key. [src: src/popup/popup.js; src/viewer/viewer.js]\n' +
    '- Download PDF uses Latin-1; Print supports Unicode. [src: src/lib/pdf.js; docs/COMPONENTS.md]\n' +
    '- There is no server, MCP runtime, datastore, or embedding pipeline. [src: docs/ARCHITECTURE.md; docs/MCP.md]\n'],
  ['llms.txt', header + `# ${manifest.name}\n\n> Browser-only YouTube caption export.\n\n` +
    '## Orientation\n\n- [Documentation index](docs/wiki/index.md)\n- [README](README.md)\n- [Components](docs/COMPONENTS.md)\n- [Development](docs/DEVELOPMENT.md)\n- [Testing](docs/TESTING.md)\n- [Privacy](PRIVACY.md)\n- [Security](docs/SECURITY.md)\n\n' +
    '## Retrieval\n\n- [Full documentation snapshots](llms-full.txt)\n- [Small summary](llms-small.txt)\n- [Sourced facts](llms-facts.txt)\n- [File index](docs/high_signal_file_index.json)\n- [Codebase map](docs/codebase-overview.md)\n'],
]);
let stale = false;
for (const [path, body] of outputs) {
  if (check) {
    if (!existsSync(join(root, path)) || read(path) !== body) { console.error(`Stale generated documentation: ${path}`); stale = true; }
  } else writeFileSync(join(root, path), body);
}
if (stale) { console.error('Run npm run docs:generate.'); process.exitCode = 1; }
else console.log(`Generated documentation ${check ? 'matches' : 'updated'} — ${files.length} maintained file entries.`);
